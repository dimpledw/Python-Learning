'''Here are three numeric data types
Integer(whole number) - 2, 1000, -12
float(decimal number) - 3.16, 372.302, 20283322.098337383
complex(real + imaginary numbers) - 2 + 3j
We can covert string to int, int to float, string to float, int to complex
'''

x = 4
y = 129.39
z = 2 + 3j
print(type(x))      # This will print class int
print(type(y))      # This will print class float
print(type(z))      # This will print class complex

# Operators

print(2+2)
print(4-3)
print(4*2)
print(7/2)      # This will print float 3.5
print(7//2)     # This will print int 3

# Use case of % can be to check if number is odd or even
print(7%2)      # This will print the remainder which is 1

print(2**3)     # 2 is the base and 3 is the exponent. This will print 8

